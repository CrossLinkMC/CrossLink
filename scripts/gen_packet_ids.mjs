// Regenerates include/crosslink/api/proto/PacketId.hpp from the vendored
// BedrockProtocol enum, so CrossLink's public API never transcribes ids by hand.
//
//   node scripts/gen_packet_ids.mjs [path/to/MinecraftPacketIds.hpp]

import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const source = resolve(
    process.argv[2] ?? ".deps/BedrockProtocol/include/sculk/protocol/codec/MinecraftPacketIds.hpp",
);
const out = resolve("include/crosslink/api/proto/PacketId.hpp");

const body = readFileSync(source, "utf8");
const start = body.indexOf("enum class MinecraftPacketIds");
const stop = body.indexOf("};", start);
if (start < 0 || stop < 0) {
    throw new Error(`cannot locate MinecraftPacketIds in ${source}`);
}

let maxId = 0;
const entries = [];
for (const line of body.slice(start, stop).split("\n").slice(1)) {
    const match = /^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(\d+)\s*,?\s*(?:\/\/\s*(.*))?$/.exec(line);
    if (!match) continue;
    const [, name, rawId, comment] = match;
    const id = Number(rawId);
    maxId = Math.max(maxId, id);
    entries.push({ name, id, comment: comment?.trim() });
}
if (entries.length === 0) throw new Error("no enumerator parsed");

const width = Math.max(...entries.map((e) => e.name.length));
const lines = entries.map((e) => {
    const padded = `${e.name} = ${e.id},`.padEnd(width + 10);
    return e.comment ? `    ${padded}// ${e.comment}` : `    ${padded.trimEnd()}`;
});

const header = `// Generated by scripts/gen_packet_ids.mjs from BedrockProtocol's
// codec/MinecraftPacketIds.hpp. Do not edit by hand.
//
// CrossLink mirrors the ids instead of re-exporting the transport library's enum
// so that the plugin ABI stays stable when the vendored protocol library moves.
// Values outside this enumeration are still valid packet ids; use
// crosslink::proto::makePacketId() / packetIdValue() to work with them.

#pragma once

#include <cstdint>

#if __has_include(<magic_enum/magic_enum.hpp>)
#include <magic_enum/magic_enum.hpp>
#endif

namespace crosslink::proto {

enum class PacketId : std::uint16_t {
${lines.join("\n")}
};

inline constexpr std::uint16_t packetIdMin = 0;
inline constexpr std::uint16_t packetIdMax = ${maxId};

[[nodiscard]] constexpr PacketId makePacketId(std::uint16_t value) noexcept {
    return static_cast<PacketId>(value);
}

[[nodiscard]] constexpr std::uint16_t packetIdValue(PacketId id) noexcept {
    return static_cast<std::uint16_t>(id);
}

} // namespace crosslink::proto

#if __has_include(<magic_enum/magic_enum.hpp>)
template <>
struct magic_enum::customize::enum_range<crosslink::proto::PacketId> {
    static constexpr int min = 0;
    static constexpr int max = ${maxId};
};
#endif
`;

writeFileSync(out, header.replaceAll("\r\n", "\n"), "utf8");
console.log(`wrote ${out}: ${entries.length} ids, max ${maxId}`);
