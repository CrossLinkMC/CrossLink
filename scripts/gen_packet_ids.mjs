// Regenerates include/crosslink/api/proto/PacketId.hpp from the vendored
// bedrock-protocol codecs, so CrossLink's public API never transcribes ids by hand.
//
//   node scripts/gen_packet_ids.mjs [path/to/generated/include/bedrock/protocol]
//
// Rules, in order:
//   1. every `struct X { static constexpr int Id = N; }` in the generated headers
//      names a packet; a trailing "Packet" is dropped from the enumerator.
//   2. several structs can share one id (version namespaces, renamed packets);
//      the alphabetically first name wins.
//   3. ids the current protocol no longer defines keep the name they already had
//      in PacketId.hpp, so historical _Deprecated entries stay readable in logs.
//   4. EndId, packetIdMax and the magic_enum range are one past the highest id.

import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { resolve, join } from "node:path";

const source = resolve(
    process.argv[2] ?? "third_party/bedrock-protocol/generated/include/bedrock/protocol",
);
const out = resolve("include/crosslink/api/proto/PacketId.hpp");

const byId = new Map();
let maxId = 0;
for (const file of readdirSync(source).filter((f) => f.endsWith(".h"))) {
    const text = readFileSync(join(source, file), "utf8");
    for (const match of text.matchAll(/struct (\w+)\s*\{\s*static constexpr int Id = (\d+);/g)) {
        const name = match[1].replace(/Packet$/, "");
        const id = Number(match[2]);
        maxId = Math.max(maxId, id);
        const previous = byId.get(id);
        if (previous === undefined || name < previous) byId.set(id, name);
    }
}
if (byId.size === 0) throw new Error(`no packet ids parsed from ${source}`);

const historical = new Map();
if (existsSync(out)) {
    const text = readFileSync(out, "utf8");
    const start = text.indexOf("enum class PacketId");
    const stop = text.indexOf("};", start);
    if (start >= 0 && stop > start) {
        for (const match of text.slice(start, stop).matchAll(/^\s*([A-Za-z_]\w*)\s*=\s*(\d+)\s*,/gm)) {
            if (match[1] !== "EndId") historical.set(Number(match[2]), match[1]);
        }
    }
}

const entries = [];
for (let id = 0; id <= maxId; ++id) {
    const name = byId.get(id) ?? historical.get(id);
    if (name !== undefined) entries.push({ name, id });
}
const endId = maxId + 1;
entries.push({ name: "EndId", id: endId });

const lines = entries.map((e) => `    ${e.name} = ${e.id},`);
const header = `// Generated by scripts/gen_packet_ids.mjs from the vendored bedrock-protocol
// codecs (third_party/bedrock-protocol). Do not edit by hand.
//
// CrossLink mirrors the ids instead of re-exporting the protocol library's types
// so that the plugin ABI stays stable when the vendored library moves. Values
// outside this enumeration are still valid packet ids; use
// crosslink::proto::makePacketId() / packetIdValue() to work with them.
//
// Where several generated structs share one id (version namespaces, renamed
// packets) the alphabetically first name wins. Ids the current protocol no longer
// defines keep their historical _Deprecated name so logs stay readable.

#pragma once

#include <cstdint>

#if __has_include(<magic_enum/magic_enum.hpp>)
#include <magic_enum/magic_enum.hpp>
#endif

namespace crosslink::proto {

enum class PacketId : std::uint16_t {
${lines.join("\n")}
};

inline constexpr std::uint16_t packetIdMin = 0;
inline constexpr std::uint16_t packetIdMax = ${endId};

[[nodiscard]] constexpr PacketId makePacketId(std::uint16_t value) noexcept {
    return static_cast<PacketId>(value);
}

[[nodiscard]] constexpr std::uint16_t packetIdValue(PacketId id) noexcept {
    return static_cast<std::uint16_t>(id);
}

} // namespace crosslink::proto

#if __has_include(<magic_enum/magic_enum.hpp>)
template <>
struct magic_enum::customize::enum_range<crosslink::proto::PacketId> {
    static constexpr int min = 0;
    static constexpr int max = ${endId};
};
#endif
`;

writeFileSync(out, header.replaceAll("\r\n", "\n"), "utf8");
console.log(`wrote ${out}: ${entries.length} ids, max ${maxId}`);